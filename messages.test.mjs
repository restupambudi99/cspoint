import assert from 'node:assert/strict';
import { openMessages } from './messages.mjs';
import { readConversation } from './read-receipts.mjs';
import { DatabaseSync } from 'node:sqlite';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const store = openMessages(':memory:');
const message = { id: 'one', jid: '628123456789@s.whatsapp.net', name: '<test>', text: 'hello', timestamp: 1 };
store.add(message); store.add(message);
assert.equal(store.thread(message.jid).length, 1);
store.add({ ...message, id: 'two', text: 'reply', outgoing: true, timestamp: 2 });
assert.equal(store.list().length, 1);
assert.equal(store.list()[0].text, 'reply');
assert.equal(store.thread(message.jid)[1].outgoing, 1);
assert.equal(store.thread('other').length, 0);
assert.equal(store.list()[0].name, '<test>', 'agent reply must not replace the customer name');
assert.equal(store.list()[0].unreadCount, 1);
let receiptKeys;
await readConversation(store, { readMessages: async keys => { receiptKeys = keys; } }, message.jid, ['one', 'two']);
assert.deepEqual(receiptKeys, [{ remoteJid: message.jid, id: 'one', fromMe: false }], 'only incoming keys are acknowledged');
assert.equal(store.list()[0].unreadCount, 0);
store.markUnread(message.jid);
assert.equal(store.list()[0].unreadCount, 1);
await readConversation(store, null, message.jid, []);
assert.equal(store.list()[0].unreadCount, 0);
store.add({ ...message, id: 'three', timestamp: 3 });
await readConversation(store, { readMessages: async () => { throw new Error('offline'); } }, message.jid, ['three']);
assert.equal(store.list()[0].unreadCount, 0, 'local read state survives receipt failure');
assert.equal(store.readKeys(message.jid, ['three']).length, 1, 'failed receipt remains retryable');
store.add({ ...message, id: 'four', timestamp: 4 });
await readConversation(store, { readMessages: async () => {} }, message.jid, ['three']);
assert.equal(store.list()[0].unreadCount, 1, 'an arriving message outside the displayed snapshot stays unread');
store.updateReceipt({ remoteJid: message.jid, id: 'two', fromMe: true }, 4);
store.updateReceipt({ remoteJid: message.jid, id: 'two', fromMe: true }, 2);
assert.equal(store.thread(message.jid).find(item => item.id === 'two').status, 4, 'late delivery event never reverses a read receipt');
store.updateReceipt({ remoteJid: message.jid, id: 'early', fromMe: true }, 4);
store.add({ ...message, id: 'early', outgoing: true, timestamp: 5 });
assert.equal(store.thread(message.jid).at(-1).status, 4, 'receipt before message insertion is retained');
const label = store.saveLabel({ name: 'Follow up', color: 'purple' });
store.setLabels(message.jid, [label.id]);
assert.equal(store.list()[0].labels[0].name, 'Follow up');
store.saveLabel({ ...label, name: 'Follow up besok', color: 'amber' });
assert.equal(store.list()[0].labels[0].color, 'amber');
assert.throws(() => store.setLabels(message.jid, ['missing']), /tidak valid/);
assert.equal(store.list()[0].labels.length, 1, 'invalid edit must preserve existing labels');
store.deleteLabel(label.id);
assert.equal(store.list()[0].labels.length, 0);
store.close();
const folder = await mkdtemp(join(tmpdir(), 'cspoint-inbox-'));
try {
  const path = join(folder, 'legacy.sqlite');
  const legacy = new DatabaseSync(path);
  legacy.exec("CREATE TABLE messages (id TEXT PRIMARY KEY,jid TEXT NOT NULL,name TEXT NOT NULL,text TEXT NOT NULL,outgoing INTEGER NOT NULL,timestamp INTEGER NOT NULL); INSERT INTO messages VALUES ('old','123@lid','Customer','Old message',0,1)");
  legacy.close();
  let persisted = openMessages(path);
  const savedLabel = persisted.saveLabel({ name: 'Retained', color: 'green' });
  persisted.setLabels('123@lid', [savedLabel.id]);
  persisted.markRead('123@lid', ['old'], true);
  persisted.close(); persisted = openMessages(path);
  assert.equal(persisted.list()[0].text, 'Old message');
  assert.equal(persisted.list()[0].unreadCount, 0);
  assert.equal(persisted.list()[0].labels[0].name, 'Retained');
  persisted.close();
} finally { await rm(folder, { recursive: true, force: true }); }
console.log('PASS: legacy migration, persisted unread/labels, customer names, real receipt keys, receipt retry and out-of-order delivery');
